def test_pdf_profile_extracts_text(tmp_path):
    pdf = tmp_path / "invoice.pdf"
    pdf.write_bytes(make_pdf(["INVOICE - Amazon", "Total: 42.00", "Thank you"]))

    profile = extract_profile(pdf)

    assert profile.kind == "pdf"
    assert "INVOICE" in profile.text_sample
    assert "Total" in profile.text_sample


def test_pdf_profile_extracts_text_from_compressed_stream(tmp_path):
    """FlateDecode streams must be decompressed (zlib) before text extraction."""
    text = b"CONFIDENTIAL REPORT 2026"
    stream = f"<< /Length {len(zlib.compress(text))} /Filter /FlateDecode >>\nstream\n".encode() + zlib.compress(text) + b"\nendstream"
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R >>",
        stream,
    ]
    out = bytearray(b"%PDF-1.4\n")
    for i, obj in enumerate(objects, start=1):
        out += f"{i} 0 obj\n".encode() + obj + b"\nendobj\n"
    out += b"trailer\n<< /Size 5 /Root 1 0 R >>\n%%EOF\n"
    pdf = tmp_path / "compressed.pdf"
    pdf.write_bytes(bytes(out))

    profile = extract_profile(pdf)

    assert profile.kind == "pdf"
    assert "CONFIDENTIAL" in profile.text_sample


