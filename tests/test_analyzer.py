def test_zip_profile_lists_manifest(tmp_path):
    import zipfile
    z = tmp_path / "bundle.zip"
    with zipfile.ZipFile(z, "w") as zf:
        zf.writestr("a.txt", "hello")
        zf.writestr("b/c.txt", "world")

    profile = extract_profile(z)

    assert profile.kind == "archive"
    assert "a.txt" in profile.metadata["members"]
    assert "b/c.txt" in profile.metadata["members"]


def test_tar_profile_lists_manifest(tmp_path):
    import tarfile
    t = tmp_path / "bundle.tar"
    with tarfile.open(t, "w") as tf:
        for name in ("one.txt", "two.txt"):
            data = b"x"
            info = tarfile.TarInfo(name)
            info.size = len(data)
            tf.addfile(info, __import__("io").BytesIO(data))

    profile = extract_profile(t)

    assert profile.kind == "archive"
    assert set(profile.metadata["members"]) == {"one.txt", "two.txt"}


